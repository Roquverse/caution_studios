/**
 * Generate 200 precomputed waveform peak samples between 0.1 and 1.0
 */
function generatePeaks(seed: number): number[] {
  const peaks: number[] = [];
  for (let i = 0; i < 200; i++) {
    const angle = (i / 200) * Math.PI * (4 + (seed % 5));
    const noise = Math.sin(angle * 2.5) * 0.3 + Math.cos(angle * 5) * 0.2;
    const base = 0.35 + Math.abs(Math.sin(angle)) * 0.45;
    const peak = Math.max(0.12, Math.min(1.0, base + noise));
    peaks.push(parseFloat(peak.toFixed(2)));
  }
  return peaks;
}

